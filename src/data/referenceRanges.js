/**
 * Helper to match an alias in raw text or table rows
 */
export function findParameterDefinition(query) {
  if (!query) return null;
  const clean = query.trim().toLowerCase();
  
  for (const key of Object.keys(MEDICAL_PARAMETERS)) {
    const item = MEDICAL_PARAMETERS[key];
    if (item.id === clean || item.name.toLowerCase().includes(clean)) {
      return item;
    }
    for (const alias of item.aliases) {
      if (clean === alias || clean.startsWith(alias) || alias.startsWith(clean)) {
        return item;
      }
    }
  }
  return null;
}
